/**
 * mulberry32 32-bit stateful PRNG
 */
export function mulberry32(seed: number): () => number {
  return function () {
    let t = (seed += 0x6d2b79f5);
    t = Math.imul(t ^ (t >>> 15), t | 1);
    t ^= t + Math.imul(t ^ (t >>> 7), t | 61);
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

/**
 * cyrb53 hash function for creating 32-bit seeds from strings
 */
export function hashString(str: string): number {
  let h1 = 0xdeadbeef;
  let h2 = 0x41c64e6d;
  for (let i = 0; i < str.length; i++) {
    const ch = str.charCodeAt(i);
    h1 = Math.imul(h1 ^ ch, 2654435761);
    h2 = Math.imul(h2 ^ ch, 1597334677);
  }
  h1 = Math.imul(h1 ^ (h1 >>> 16), 2246822507);
  h1 ^= Math.imul(h2 ^ (h2 >>> 13), 3266489909);
  h2 = Math.imul(h2 ^ (h2 >>> 16), 2246822507);
  h2 ^= Math.imul(h1 ^ (h1 >>> 13), 3266489909);
  return 4294967296 * (2097151 & h2) + (h1 >>> 0);
}

/**
 * Fisher-Yates shuffle with optional PRNG
 */
export function shuffle<T>(array: T[], prng?: () => number): T[] {
  const result = [...array];
  const rand = prng || Math.random;
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(rand() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

/**
 * Returns today's local date string formatted as YYYY-MM-DD
 */
export function getLocalDateString(): string {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

/**
 * Selects a deterministic song index for the Daily mode given a date string and pool length
 */
export function getDailySongIndex(poolLength: number, dateStr: string = getLocalDateString()): number {
  if (poolLength <= 0) return 0;
  const seed = hashString(`rapguess-daily-${dateStr}`);
  const prng = mulberry32(seed);
  return Math.floor(prng() * poolLength);
}
